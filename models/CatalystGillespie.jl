module CatalystGillespie

using Catalyst, ModelingToolkit, Symbolics, SymbolicUtils
using SymbolicUtils: iscall, operation, arguments
const MT = ModelingToolkit

export writegillespie

function fixedstring(f::Real)
    isinteger(float(f)) && abs(float(f)) < 1e15 && return string(Int(float(f)), ".0")
    s = string(float(f))
    (occursin('e', s) || occursin('E', s)) || return s
    m, e = split(replace(s, 'E' => 'e'), 'e')
    exp10 = parse(Int, e)
    neg = startswith(m, '-')
    neg && (m = m[2:end])
    ip, fp = occursin('.', m) ? split(m, '.') : (m, "")
    digits = ip * fp
    point = length(ip) + exp10
    out = if point <= 0
        "0." * "0"^(-point) * digits
    elseif point >= length(digits)
        digits * "0"^(point - length(digits)) * ".0"
    else
        digits[1:point] * "." * digits[point+1:end]
    end
    (neg ? "-" : "") * out
end

const CXX = Dict(:+ => "+", :- => "-", :* => "*", :/ => "/")
const CXXFUN = Dict(:abs => "fabs", :min => "std::min", :max => "std::max",
                    :exp => "exp", :log => "log", :sqrt => "sqrt")

constvalue(ex) = begin
    ex isa Number && return float(ex)
    isempty(Symbolics.get_variables(ex)) || return nothing
    v = try
        Base.eval(@__MODULE__, Symbolics.toexpr(ex))
    catch
        return nothing
    end
    v isa Number ? float(v) : nothing
end

function cxx(ex, ids)
    ex isa Number && return fixedstring(ex)
    u = MT.unwrap(ex)
    haskey(ids, u) && return ids[u]
    let c = constvalue(u)
        isnothing(c) || return fixedstring(c)
    end
    u isa Number && return fixedstring(u)
    if !iscall(u)
        v = try
            Symbolics.toexpr(u)
        catch
            nothing
        end
        v isa Number && return fixedstring(v)
        error("no state id for symbol $u")
    end
    op = operation(u)
    args = arguments(u)
    name = nameof(op)
    if name === :ifelse
        return string("((", cxx(args[1], ids), ") ? (", cxx(args[2], ids),
                      ") : (", cxx(args[3], ids), "))")
    end
    if name === :^
        e = constvalue(args[2])
        e == 1 && return cxx(args[1], ids)
        e == 2 && return string("(", cxx(args[1], ids), " * ", cxx(args[1], ids), ")")
        e == 0 && return "1.0"
        return string("pow(", cxx(args[1], ids), ", ", cxx(args[2], ids), ")")
    end
    if haskey(CXXFUN, name)
        length(args) == 1 && return string(CXXFUN[name], "(", cxx(args[1], ids), ")")
        return string(CXXFUN[name], "(", cxx(args[1], ids), ", ", cxx(args[2], ids), ")")
    end
    if haskey(CXX, name)
        length(args) == 1 && name === :- && return string("(-", cxx(args[1], ids), ")")
        return string("(", join((cxx(a, ids) for a in args), " $(CXX[name]) "), ")")
    end
    error("unsupported function for C++ propensity: $name")
end

function cleanname(x)
    s = replace(string(x), "(t)" => "", "\u208a" => ".")
    m = match(r"^var\"(.*)\"$", s)
    isnothing(m) ? s : m.captures[1]
end

rstring(s) = string('"', replace(string(s), "\\" => "\\\\", "\"" => "\\\""), '"')

function writegillespie(rs::Catalyst.ReactionSystem, path::AbstractString;
                        parameter_values = Dict(), initial_amounts = Dict(),
                        constant_species = String[], ratelaw = Catalyst.oderatelaw)
    sys = Catalyst.flatten(rs)
    MT.iscomplete(sys) || (sys = MT.complete(sys))
    sp = MT.unknowns(sys)

    frozen = Set(constant_species)
    isfrozen(s) = MT.getname(s) in map(Symbol, constant_species) ||
                  string(s) in frozen ||
                  replace(string(s), "(t)" => "") in frozen

    dynamic = [s for s in sp if !isfrozen(s)]
    # fixed-width ids: GillespieSSA2 substitutes names into C++ textually, so
    # s1 would corrupt s10 into state[1]0
    ids = Dict{Any,String}()
    names = String[]
    for (i, s) in enumerate(dynamic)
        id = "s" * lpad(i, 5, '0')
        ids[MT.unwrap(s)] = id
        push!(names, id)
    end

    lookup(tbl, sym) = begin
        u = MT.unwrap(sym)
        for k in (u, sym, Symbol(sym), string(sym))
            haskey(tbl, k) && return float(tbl[k])
        end
        0.0
    end

    # frozen pools become literal constants in the propensity strings
    for s in sp
        isfrozen(s) || continue
        ids[MT.unwrap(s)] = fixedstring(lookup(initial_amounts, s))
    end

    law = ratelaw
    rxs = Catalyst.reactions(sys)
    specidx = Dict(MT.unwrap(s) => i for (i, s) in enumerate(dynamic))

    open(path, "w") do io
        println(io, "# generated by models/export.jl gillespie -- do not edit")
        println(io, "state_ids <- c(", join(rstring.(names), ", "), ")")
        println(io, "state_names <- c(",
                join((rstring(cleanname(x)) for x in dynamic), ", "),
                ")")
        println(io, "initial_state <- c(",
                join((string(round(Int, lookup(initial_amounts, s))) for s in dynamic), ", "),
                ")")
        println(io, "names(initial_state) <- state_ids")
        println(io, "reactions <- list(")
        for (j, rx) in enumerate(rxs)
            prop = cxx(law(rx), ids)
            eff = Dict{Int,Int}()
            for (s, c) in zip(rx.substrates, rx.substoich)
                u = MT.unwrap(s)
                haskey(specidx, u) || continue
                eff[specidx[u]] = get(eff, specidx[u], 0) - Int(c)
            end
            for (s, c) in zip(rx.products, rx.prodstoich)
                u = MT.unwrap(s)
                haskey(specidx, u) || continue
                eff[specidx[u]] = get(eff, specidx[u], 0) + Int(c)
            end
            filter!(p -> p.second != 0, eff)
            effstr = join(("$(rstring(names[k])) = $(v)" for (k, v) in sort(collect(eff))), ", ")
            println(io, "  GillespieSSA2::reaction(propensity = ", rstring(prop),
                    ", effect = c(", effstr, "), name = ", rstring("r$j"), ")",
                    j == length(rxs) ? "" : ",")
        end
        println(io, ")")
    end
    path
end

end
